#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const repoRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(?:[A-Za-z]:)/u, (value) => value.slice(1))), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const catalogIndex = args.indexOf('--catalog');
const catalogPath = path.resolve(catalogIndex >= 0 && args[catalogIndex + 1]
  ? args[catalogIndex + 1]
  : path.join(repoRoot, '..', 'RDC-Agent-Tools', 'spec', 'tool_catalog.json'));
const membersPath = path.join(repoRoot, 'resources', 'agent-runtime', 'rdx-tool-guide-members.json');

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8').replace(/^\uFEFF/u, ''));
}

function fail(message) {
  throw new Error(`[rdx-tool-guides] ${message}`);
}

function sample(schema, key = '') {
  if (Array.isArray(schema?.enum) && schema.enum.length) return schema.enum[0];
  if (Array.isArray(schema?.oneOf) && schema.oneOf.length) return sample(schema.oneOf[0], key);
  switch (schema?.type) {
    case 'string':
      if (/event|count|index|slot|mip|slice|sample/iu.test(key)) return '0';
      if (/resource|texture|buffer|shader/iu.test(key)) return 'ResourceId::1';
      if (/path/iu.test(key)) return 'intermediate/evidence.bin';
      if (/stage/iu.test(key)) return 'ps';
      return 'value';
    case 'integer': return Math.max(Number(schema.minimum ?? 0), /event/iu.test(key) ? 1 : 0);
    case 'number': return Math.max(Number(schema.minimum ?? 0), 0);
    case 'boolean': return false;
    case 'array': return Number(schema.minItems ?? 0) > 0 ? [sample(schema.items ?? {}, key)] : [];
    case 'object': {
      const result = {};
      for (const required of schema.required ?? []) result[required] = sample(schema.properties?.[required] ?? {}, required);
      return result;
    }
    default: return null;
  }
}

function validate(value, schema, label) {
  if (schema?.oneOf) {
    if (schema.oneOf.filter((branch) => { try { validate(value, branch, label); return true; } catch { return false; } }).length !== 1) fail(`${label} must match exactly one oneOf branch`);
  }
  if (schema?.not) { let matches = true; try { validate(value, schema.not, label); } catch { matches = false; } if (matches) fail(`${label} matches a forbidden combination`); }
  if (value && typeof value === 'object' && !Array.isArray(value)) for (const required of schema?.required ?? []) if (!(required in value)) fail(`${label}.${required} is required`);
  if (schema?.enum && !schema.enum.some((entry) => JSON.stringify(entry) === JSON.stringify(value))) fail(`${label} is outside enum`);
  if (schema?.type === 'object') {
    if (!value || typeof value !== 'object' || Array.isArray(value)) fail(`${label} must be object`);
    for (const required of schema.required ?? []) if (!(required in value)) fail(`${label}.${required} is required`);
    if (schema.additionalProperties === false) for (const key of Object.keys(value)) if (!(key in (schema.properties ?? {}))) fail(`${label}.${key} is unknown`);
    for (const [key, child] of Object.entries(value)) validate(child, schema.properties?.[key] ?? {}, `${label}.${key}`);
  } else if (schema?.type === 'array') {
    if (!Array.isArray(value)) fail(`${label} must be array`);
    if (value.length < Number(schema.minItems ?? 0)) fail(`${label} has too few items`);
    if (schema.maxItems !== undefined && value.length > schema.maxItems) fail(`${label} has too many items`);
    value.forEach((entry, index) => validate(entry, schema.items ?? {}, `${label}[${index}]`));
  } else if (schema?.type === 'string' && typeof value !== 'string') fail(`${label} must be string`);
  else if (schema?.type === 'integer' && !Number.isInteger(value)) fail(`${label} must be integer`);
  else if (schema?.type === 'number' && typeof value !== 'number') fail(`${label} must be number`);
  else if (schema?.type === 'boolean' && typeof value !== 'boolean') fail(`${label} must be boolean`);
}

function md(value) {
  return String(value ?? '').replace(/\|/gu, '\\|').replace(/<br\s*\/?>/giu, '; ').replace(/\r?\n/gu, ' ');
}

function failureNotes(tool) {
  const notes = ['参数、身份或前置条件不满足时会返回 canonical error；合法空结果与读取失败不能互换。'];
  if ((tool.effects ?? []).includes('artifact_write')) notes.push('写文件需要已批准的输出路径；写入失败或取消不能当作证据已保存。');
  if ((tool.effects ?? []).some((effect) => ['shader_replacement', 'shader_debug'].includes(effect))) notes.push('后端不支持、缺调试信息、编译或替换失败时必须保留 unavailable/error；变更只有主进程签名回执能进入实验验收。');
  if (tool.name.startsWith('rd.perf.')) notes.push('计数器可用性由当前驱动决定；空采样、读取失败和整帧时间是不同语义。');
  if (tool.name === 'rd.texture.get_pixel_history') notes.push('像素历史支持显式 texture 或当前输出目标，互斥目标参数不能同时提供。');
  if (tool.name === 'rd.export.mesh') notes.push('只支持 post-VS、OBJ、32 位浮点位置和受支持的 primitive topology；其它格式或属性必须返回 unsupported，不能写伪 OBJ。');
  return notes;
}

function renderGuide(guide, toolsByName, catalog) {
  const lines = [
    '<!-- Generated by scripts/generate-rdx-tool-guides.mjs. Do not edit by hand. -->',
    '',
    `# ${guide.title}`,
    '',
    `Current catalog fingerprint: \`${catalog.fingerprint}\`. 本参考只覆盖该专业需要的操作；它提供知识，不授予权限。执行时仍以 prepareTurn 冻结的同一 CLI catalog 和主进程审批为准。`,
    '',
    '所有 `shell.rdx` 示例都省略由主进程注入的 `session_id` / `capture_file_id` / context 身份。不要把示例补成可覆盖其它会话的身份。共享发现、错误恢复、输出与副作用规则见 `$rdx-cli-shell`。',
    '',
  ];
  for (const name of guide.operations) {
    const tool = toolsByName.get(name);
    const schema = tool.input_schema ?? { type: 'object', properties: {}, required: [], additionalProperties: false };
    const exampleArgs = {};
    const requiredNames = [...new Set([...(schema.required ?? []), ...(schema.oneOf?.[0]?.required ?? [])])];
    for (const required of requiredNames) {
      if (!['session_id', 'context_id', 'capture_file_id'].includes(required)) exampleArgs[required] = sample(schema.properties?.[required] ?? {}, required);
    }
    const validationArgs = { ...exampleArgs };
    if ((schema.required ?? []).includes('session_id')) validationArgs.session_id = 'session-example';
    if ((schema.required ?? []).includes('context_id')) validationArgs.context_id = 'context-example';
    if (requiredNames.includes('capture_file_id')) validationArgs.capture_file_id = 'capture-example';
    validate(validationArgs, schema, name);
    lines.push(`## \`${name}\``, '', md(tool.description), '', '| 参数 | 必需 | 约束 |', '|---|---:|---|');
    for (const [key, parameter] of Object.entries(schema.properties ?? {})) {
      const constraints = [parameter.type, parameter.enum ? `enum=${parameter.enum.join(',')}` : '', parameter.minimum !== undefined ? `min=${parameter.minimum}` : '', parameter.maximum !== undefined ? `max=${parameter.maximum}` : '', parameter.description].filter(Boolean).join('; ');
      lines.push(`| \`${key}\` | ${(schema.required ?? []).includes(key) ? '是' : '否'} | ${md(constraints)} |`);
    }
    lines.push('', `**结果解释：** ${md(tool.returns_raw) || '读取 canonical envelope 的 data / error / meta。'}`, '');
    if ((tool.prerequisites ?? []).length) lines.push(`**前置条件：** ${(tool.prerequisites ?? []).map((entry) => md(entry.reason || entry.requires)).join('；')}`, '');
    lines.push(`**影响：** \`${(tool.effects ?? []).join('`, `') || 'none'}\`。`, '', '**失败与限制：**');
    for (const note of failureNotes(tool)) lines.push(`- ${note}`);
    lines.push('', '**`shell.rdx` 示例：**', '', '```json', JSON.stringify({ rdx: { operation: name, args: exampleArgs } }), '```', '');
  }
  return lines.join('\n').trimEnd() + '\n';
}

if (!fs.existsSync(catalogPath)) fail(`catalog not found: ${catalogPath}; pass --catalog <RDC-Agent-Tools/spec/tool_catalog.json>`);
const catalog = readJson(catalogPath);
const members = readJson(membersPath);
if (!Array.isArray(catalog.tools) || !catalog.tools.length || catalog.tool_count !== catalog.tools.length) fail('catalog count does not match operation definitions');
const toolsByName = new Map(catalog.tools.map((tool) => [tool.name, tool]));
if (toolsByName.size !== catalog.tools.length) fail('catalog contains duplicate operation names');
for (const [profile, guideConfig] of Object.entries(members.guides ?? {})) {
  const operations = guideConfig.operations ?? [];
  if (!operations.length || new Set(operations).size !== operations.length) fail(`${profile} members must be non-empty and unique`);
  for (const name of operations) {
    if (!toolsByName.has(name)) fail(`${profile} references unknown operation ${name}`);
    const tool = toolsByName.get(name);
    if (!['replay', 'capture', 'global', 'context'].includes(tool.scope) || tool.effects.some(effect => !['replay_position', 'replay_position_temporary', 'artifact_write', 'context_metadata', 'shader_debug', 'shader_replacement'].includes(effect))) fail(`${profile} must not document application-owned lifecycle/discovery operation ${name}`);
  }
  const outputPath = path.join(repoRoot, 'resources', 'agent-runtime', 'skills', guideConfig.skillId, 'references', 'tools.md');
  const output = renderGuide(guideConfig, toolsByName, catalog);
  if (check) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8').replace(/^\uFEFF/u, '') !== output) fail(`stale generated reference: ${outputPath}`);
  } else {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, output, 'utf8');
  }
}
console.log(`[rdx-tool-guides] ${check ? 'fresh' : 'generated'}: ${Object.keys(members.guides).length} guides from ${catalog.fingerprint}`);
