export const LIVE_PLAN_RELATIVE_PATH = 'plan.md';
export const LIVE_PLAN_URI = formatSessionArtifactUri('plans', LIVE_PLAN_RELATIVE_PATH);

export function composePlanMarkdown(input: { title: string; summary: string[]; content: string; taskRequirements?: PlanTaskRequirement[]; investigation?: InvestigationPlanContract | null }): string {
  const title = input.title.trim();
  const bullets = input.summary.map((line) => `- ${line.trim()}`).join('\n');
  const body = input.content.replace(/\r\n/g, '\n').trim();
  if (body.includes(PLAN_TASK_REQUIREMENTS_HEADING)) throw new AppError('PLAN_TASK_REQUIREMENTS_INVALID', 'task contracts must be generated from requiredTaskIds, not supplied as Markdown.');
  if (body.includes(PLAN_INVESTIGATION_HEADING)) throw new AppError('PLAN_INVESTIGATION_INVALID', 'investigation contract is generated by the host, not supplied as Markdown.');
  assertReaderFacingPlan({ title, summary: input.summary, content: body });
  const investigation = input.investigation ? `\n${renderInvestigationPlanContract(input.investigation)}` : '';
  const tasks = input.taskRequirements?.length ? `\n${renderPlanTaskRequirements(input.taskRequirements)}` : '';
  return `# ${title}\n\n${bullets}\n\n${body}\n${investigation}${tasks}`;
}

/** Reader-facing sections; the execution appendix is not part of the preview projection. */
export function sectionsFromMarkdown(markdown: string): PlanReviewSection[] {
  const text = splitPlanAppendix(markdown).body;
  const matches = [...text.matchAll(/^##[ \t]+(.+)$/gm)];
  if (matches.length === 0) {
    const body = text.replace(/^#\s+.+\n+/, '').trim();
    return body ? [{ heading: '', body }] : [];
  }
  return matches.map((match, index) => {
    const heading = match[1].trim();
    const start = match.index + match[0].length;
    const end = index + 1 < matches.length ? matches[index + 1].index : text.length;
    return { heading, body: text.slice(start, end).replace(/^\n+/, '').trim() };
  });
}

export interface StagedFrozenPlan {
  uri: string;
  markdown: string;
  hash: string;
  taskRequirements: PlanTaskRequirement[];
}

export class PlanArtifactWriter {
  constructor(private readonly resolver: SessionArtifactResolver = sessionArtifactResolver) {}

  writeLivePlan(sessionId: string, markdown: string): SessionArtifactWriteResult {
    return this.resolver.write(sessionId, LIVE_PLAN_URI, markdown);
  }

  /** Reads and checks the live plan the person approved and names its frozen copy; nothing is written yet. */
  stageFrozenPlan(sessionId: string, expectedHash: string): StagedFrozenPlan {
    const { markdown, hash } = this.readMarkdown(sessionId, LIVE_PLAN_URI, expectedHash);
    parseInvestigationPlanContract(markdown);
    const stamp = new Date().toISOString().replace(/[:.]/g, '');
    const uri = formatSessionArtifactUri('plans', `plan-${stamp}-${shortArtifactHash(hash)}.md`);
    return { uri, markdown, hash, taskRequirements: parsePlanTaskRequirements(markdown) };
  }

  writeFrozenPlan(sessionId: string, staged: StagedFrozenPlan): void {
    if (this.resolver.write(sessionId, staged.uri, staged.markdown).hash === staged.hash) return;
    this.discardFrozenPlan(sessionId, staged.uri);
    throw new AppError('PLAN_WRITE_VERIFY_FAILED', 'the frozen copy differs from the reviewed plan.');
  }

  /** Rollback of `writeFrozenPlan`: the copy of an approval that did not commit is not history. */
  discardFrozenPlan(sessionId: string, uri: string): void {
    fs.rmSync(this.resolver.resolve(sessionId, uri).absolutePath, { force: true });
    this.resolver.reconcileUsage(sessionId);
  }

  readMarkdown(sessionId: string, uri: string, expectedHash: string): { markdown: string; hash: string; uri: string } {
    const resolved = this.resolver.resolve(sessionId, uri);
    if (!fs.existsSync(resolved.absolutePath)) {
      throw new AppError('PLAN_NOT_FOUND', uri);
    }
    const bytes = fs.readFileSync(resolved.absolutePath);
    const hash = crypto.createHash('sha256').update(bytes).digest('hex');
    if (normalizeSha256(expectedHash) !== hash) {
      throw new AppError('PLAN_HASH_MISMATCH', 'sha256 does not match expectedHash.');
    }
    return { markdown: bytes.toString('utf8'), hash, uri: resolved.uri };
  }
}

export const planArtifactWriter = new PlanArtifactWriter();
