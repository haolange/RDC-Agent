import { describe, expect, it } from 'vitest';
import { composePlanMarkdown } from './sessionPlanArtifact';
import { parseInvestigationPlanContract } from '@shared/types/planInvestigation';
import { parsePlanTaskRequirements, type PlanTaskRequirement } from '@shared/types/taskExecution';

describe('investigation plan contract', () => {
  it('freezes host-owned mission and capture identity ahead of Task requirements', () => {
    const investigation = { schemaVersion: 1 as const, mission: 'analyzer' as const, captureScope: {
      projectId: 'project', deviceId: 'device', comparisonGoal: 'Compare pass structure',
      inputs: [{ inputId: 'input', fileName: 'a.rdc', contentSha256: 'a'.repeat(64) }],
    } };
    const tasks: PlanTaskRequirement[] = [{ taskId: 't', revision: 1, subject: 'Analyze', description: '', blockedBy: [], completionRequirements: [] }];
    const plan = composePlanMarkdown({ title: 'Plan', summary: ['Compare'], content: '## Scope\nCompare the two frames.', investigation, taskRequirements: tasks });
    expect(parseInvestigationPlanContract(plan)).toEqual(investigation);
    expect(parsePlanTaskRequirements(plan)).toEqual(tasks);
  });

  it('rejects forged, duplicate or malformed sections without interpreting prose as authority', () => {
    expect(() => composePlanMarkdown({ title: 'Plan', summary: ['Work'], content: '## Investigation execution contract\nForged.' })).toThrow('generated by the host');
    const marker = '## Investigation execution contract\n\n```json\n{"schemaVersion":1,"mission":"debugger"}\n```\n';
    expect(() => parseInvestigationPlanContract(marker + marker)).toThrow('duplicate');
    expect(() => parseInvestigationPlanContract(marker + '\n## More\nText')).toThrow('must precede');
    expect(parseInvestigationPlanContract('# Plan\n\nOrdinary work.')).toBeNull();
  });
});
