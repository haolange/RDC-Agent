export type ErrorCategory = keyof typeof ERROR_CODES_BY_CATEGORY;
export type ErrorCode = (typeof ERROR_CODES_BY_CATEGORY)[ErrorCategory][number];

const CATEGORY_BY_CODE: ReadonlyMap<string, ErrorCategory> = new Map(
  (Object.entries(ERROR_CODES_BY_CATEGORY) as [ErrorCategory, readonly ErrorCode[]][])
    .flatMap(([category, codes]) => codes.map((code) => [code, category] as const)),
);

export function isErrorCode(value: string): value is ErrorCode {
  return CATEGORY_BY_CODE.has(value);
}

export function errorCategory(code: ErrorCode): ErrorCategory {
  return CATEGORY_BY_CODE.get(code)!;
}
